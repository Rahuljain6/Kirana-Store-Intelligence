-- Q26. Find the top-selling product in each category.

WITH ProductSales AS (
    SELECT
        p.Product_ID,
        p.Product_Name,
        p.Category,
        SUM(s.Quantity) AS Total_Sold
    FROM products p
    JOIN sales s
    ON p.Product_ID = s.Product_ID
    GROUP BY
        p.Product_ID,
        p.Product_Name,
        p.Category
),
RankedProducts AS (
    SELECT *,
        DENSE_RANK() OVER (
            PARTITION BY Category
            ORDER BY Total_Sold DESC
        ) AS Product_Rank
    FROM ProductSales
)
SELECT *
FROM RankedProducts
WHERE Product_Rank = 1;


-- Q27. Calculate running monthly revenue.

WITH MonthlyRevenue AS (
    SELECT
        DATE_FORMAT(
            STR_TO_DATE(Sale_Date, '%Y-%m-%d'),
            '%Y-%m'
        ) AS Sales_Month,
        SUM(Revenue) AS Revenue
    FROM sales
    GROUP BY Sales_Month
)
SELECT *,
    SUM(Revenue) OVER (
        ORDER BY Sales_Month
    ) AS Running_Revenue
FROM MonthlyRevenue;


-- Q28. Find products with profit margin greater than 20%.

SELECT
    p.Product_Name,
    p.Cost_Price,
    p.Selling_Price,
    ROUND(
        ((p.Selling_Price - p.Cost_Price)
        / NULLIF(p.Selling_Price, 0)) * 100,
        2
    ) AS Profit_Margin
FROM products p
WHERE p.Selling_Price > 0
AND (
    (p.Selling_Price - p.Cost_Price)
    / p.Selling_Price
) * 100 > 20;


