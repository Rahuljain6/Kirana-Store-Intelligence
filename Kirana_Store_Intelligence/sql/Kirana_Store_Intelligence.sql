-- Q35. Find products with inventory below reorder level.

SELECT
    p.Product_Name,
    i.Stock_Quantity,
    i.Reorder_Level,
    (i.Reorder_Level - i.Stock_Quantity) AS Stock_Shortage
FROM inventory i
JOIN products p
ON i.Product_ID = p.Product_ID
WHERE i.Stock_Quantity < i.Reorder_Level;

